/**
 * What the tracker app sends to /api/tracker/*.
 *
 * These mirror the serde types in crates/telemetry/src/tracker.rs and
 * apps/tracker/src-tauri/src/api.rs field for field (snake_case, like serde).
 * Change both sides together; the shared fixture
 * crates/telemetry/tests/fixtures/job-upload.json is parsed by tests on both sides.
 */
import { z } from "zod";

export const GameSchema = z.enum(["ets2", "ats"]);
export type Game = z.infer<typeof GameSchema>;

/** `JobInfo` in crates/telemetry/src/lib.rs. */
export const JobInfoSchema = z.object({
  source_city: z.string().min(1).max(100),
  destination_city: z.string().min(1).max(100),
  source_company: z.string().max(100),
  destination_company: z.string().max(100),
  cargo: z.string().min(1).max(100),
  cargo_mass_kg: z.number().nonnegative(),
  /** km, for both games. */
  planned_distance_km: z.number().nonnegative(),
  /** In the game's currency: EUR (ETS2) or USD (ATS). */
  income: z.number().int(),
});

/** `FinishedJob` in crates/telemetry/src/tracker.rs. */
export const FinishedJobSchema = z.object({
  game: GameSchema,
  job: JobInfoSchema,
  status: z.enum(["delivered", "cancelled"]),
  driven_km: z.number().nonnegative(),
  odometer_start_km: z.number().nonnegative(),
  odometer_end_km: z.number().nonnegative(),
  max_speed_kmh: z.number().nonnegative(),
  /** 0.0 to 1.0 */
  cargo_damage: z.number().min(0).max(1),
  /** Milliseconds since the tracker started; only differences are meaningful. */
  started_at_ms: z.number().int().nonnegative(),
  finished_at_ms: z.number().int().nonnegative(),
});
export type FinishedJob = z.infer<typeof FinishedJobSchema>;

/** Body of POST /api/tracker/jobs (`JobUpload` in the tracker app). */
export const JobUploadSchema = z.object({
  /** Generated by the tracker when the job finishes; retries reuse it. */
  client_job_id: z.uuid(),
  started_at: z.iso.datetime({ offset: true }),
  finished_at: z.iso.datetime({ offset: true }),
  multiplayer: z.boolean().default(false),
  job: FinishedJobSchema,
});
export type JobUpload = z.infer<typeof JobUploadSchema>;

/** Body of POST /api/tracker/position, sent every 5 s while driving. */
export const PositionUpdateSchema = z.object({
  game: GameSchema,
  multiplayer: z.boolean().default(false),
  /** TruckersMP server name, when known. */
  server: z.string().max(100).nullable().default(null),
  x: z.number(),
  z: z.number(),
  speed_kmh: z.number().nonnegative(),
  at: z.iso.datetime({ offset: true }),
});
export type PositionUpdate = z.infer<typeof PositionUpdateSchema>;

/** POST /api/tracker/pair/start */
export const PairStartSchema = z.object({
  device_name: z.string().min(1).max(100),
  app_version: z.string().max(40).optional(),
});
export const PairStartResponseSchema = z.object({
  device_code: z.string(),
  user_code: z.string(),
  verification_url: z.url(),
  expires_in: z.number().int(),
  interval: z.number().int(),
});

/** POST /api/tracker/pair/poll */
export const PairPollSchema = z.object({ device_code: z.string().min(1) });
export const PairPollResponseSchema = z.discriminatedUnion("status", [
  z.object({ status: z.literal("pending") }),
  z.object({ status: z.literal("expired") }),
  z.object({ status: z.literal("approved"), token: z.string(), driver_name: z.string() }),
]);
